test("el tour de Control móvil usa acciones reales de la APK", () => {
  const tours = fs.readFileSync("lib/tours.ts", "utf8")
  const control = fs.readFileSync("app/control/page.tsx", "utf8")
  const tourUi = fs.readFileSync("components/OnboardingTour.tsx", "utf8")
  const inicio = tours.indexOf("export const TOUR_CONTROL_MOBILE")
  const fin = tours.indexOf("// Genera los pasos según plataforma")
  const mobile = tours.slice(inicio, fin)
  assert.ok(inicio >= 0 && fin > inicio)
  assert.doesNotMatch(mobile, /Electron|Abrir el Proyector|segundo monitor/)
  assert.match(mobile, /Ir a la lista del culto/)
  assert.match(mobile, /scroll-lista/)
  assert.match(control, /tour-control-mobile-v2/)
  assert.match(control, /data-tour="controles-extra-mobile"/)
  assert.match(tourUi, /calc\(100vw - 24px\)/)
})

