test("Control conserva la lista por iglesia y recupera la presencia del proyector", () => {
  const control = fs.readFileSync("app/control/page.tsx", "utf8")
  const main = fs.readFileSync("electron/main.js", "utf8")
  assert.match(control, /selah-lista-culto-\$\{igId\}/)
  assert.match(control, /items:lista, listaId:listaIdActual, nombre:nombreCulto/)
  assert.match(control, /s\.on\("estado-presencia"/)
  assert.match(main, /const presenciaSala = \(sala\)/)
  assert.match(main, /controlEscritorioConectado:/)
  assert.match(main, /mainWindow\.webContents\.executeJavaScript/)
  assert.match(main, /http:\/\/localhost:3000\/proyectar/)
  assert.match(main, /socket\.emit\("estado-presencia", presenciaSala\(salaFinal\)\)/)
  assert.match(main, /setImmediate\(\(\) => emitirPresenciaSala\(sala\)\)/)
  assert.match(control, /puedeAbrirProyector: navigator\.userAgent\.includes\("Electron"\)/)
  assert.match(control, /buscarServidorEnRed/)
  assert.match(control, /setInterval\(\(\) => void sondearServidor\(\), 5000\)/)
  assert.match(control, /socketRef2\.current\?\.emit\("sincronizar-lista"/)
  assert.match(main, /socket\.on\("sincronizar-lista"/)
  assert.match(main, /revision:\+\+revisionListaSala/)
  assert.match(main, /io\.to\(sala\)\.emit\("lista-sincronizada"/)
  assert.doesNotMatch(control, /esCapacitor && !ip\)[\s\S]{0,100}return/)
})
